  function scoreSparseCurrent(
    currentFeature,
    state = loadState(),
  ) {
    if (currentFeature.length !== state.sparseFeatureCount) {
      throw new Error(
        "jump sparse feature length mismatch: " +
          currentFeature.length +
          " != " +
          state.sparseFeatureCount,
      );
    }
    let score = state.bias;
    for (let slot = 0; slot < state.sparseFeatureCount; slot += 1) {
      const standardized =
        (currentFeature[slot] - state.means[slot]) /
        state.scales[slot];
      score +=
        state.weights[slot] *
        Math.max(-5, Math.min(5, standardized));
    }
    return score;
  }

